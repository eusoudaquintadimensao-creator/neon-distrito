const puppeteer = require('puppeteer-core');
const fs = require('fs');
const URL = 'https://eusoudaquintadimensao-creator.github.io/neon-distrito/?q=low&cb=' + Date.now();
const SH = '/workspace/jogo-cyberpunk/screenshots/';
const [,, W = 1280, H = 720, out = 'd'] = process.argv;
const mobile = Math.min(+W, +H) < 600;
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--disable-dev-shm-usage', '--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage();
  await page.setViewport({ width: +W, height: +H, isMobile: mobile, hasTouch: mobile, deviceScaleFactor: mobile ? 2 : 1 });
  if (mobile) await page.setUserAgent('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1');
  const errs = [], bad = [];
  page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  page.on('pageerror', e => errs.push('PAGE: ' + e.message));
  page.on('response', r => { const s = r.status(); if (s >= 400 && !/favicon/.test(r.url())) bad.push(s + ' ' + r.url()); });
  await page.goto(URL, { waitUntil: 'load', timeout: 120000 });
  await page.waitForFunction('window.MBD_READY === true', { timeout: 120000 });
  await page.evaluate(() => { const h = MBD.home && MBD.home(); if (h && h.data) h.data.intro = true; });
  await page.screenshot({ path: `${SH}live-neon-${out}-menu.png` });
  await page.click('#play'); await sleep(2500);
  const info = await page.evaluate(async () => {
    const t = await (await fetch('./sw.js', { cache: 'no-store' })).text();
    const S = MBD.serp && MBD.serp();
    return { title: document.title, sw: (t.match(/neon-dist-v[0-9][^']+/)||[])[0], hasSerp: !!S, bar: S && S.venue && S.venue.name, qSerp: !!document.getElementById('qSerp'), keys: Object.keys(localStorage), hour: MBD.state.hour, weather: window.__G.env.weather, holos: (window.__G.world.dyn && window.__G.world.dyn.holos || []).length, hovers: (window.__G.traffic.cars.filter(c => c.hover)||[]).length };
  });
  await page.evaluate(() => { MBD.setHour(21.8); MBD.weather('chuva'); MBD.teleport(-420, 80, Math.PI * 0.7); MBD.sim(30, 1/30); });
  await sleep(2200);
  await page.screenshot({ path: `${SH}live-neon-${out}-nucleo.png` });
  await page.evaluate(() => { MBD.serp().go(); MBD.setHour(21.5); MBD.sim(20, 1/30); });
  await sleep(2200);
  await page.screenshot({ path: `${SH}live-neon-${out}-plasma.png` });
  const e2 = errs.filter(e => !/favicon|ERR_FILE_NOT_FOUND|net::/.test(e));
  const fail = [];
  if (info.title !== 'Neon Distrito') fail.push('title '+info.title);
  if (info.sw !== 'neon-dist-v1-2026-11-13') fail.push('SW '+info.sw);
  if (info.bar !== 'Bar da Antena') fail.push('bar '+info.bar);
  if (e2.length) fail.push('errs '+JSON.stringify(e2));
  if (bad.length) fail.push('http '+JSON.stringify(bad));
  const R = { ok: fail.length===0, fail, info, errs: e2, bad };
  fs.writeFileSync(`${SH}live-neon-${out}.json`, JSON.stringify(R, null, 1));
  console.log(JSON.stringify(R, null, 1));
  await browser.close();
  process.exit(R.ok?0:1);
})().catch(e => { console.error('FATAL', e); process.exit(2); });
